// Generates docs/harness-support.md from the adapter registry's harness
// metadata. Hand-written doc snippets keep their own shape; their range
// literals are pinned by scripts/check-version-literals.mjs instead. Run
// after `pnpm build` (imports the built CLI):
//
//   node scripts/generate-harness-support.mjs
//
// CI runs it and fails on any resulting diff, the same discipline as the
// committed-artifact byte gate: what the docs claim about versions is derived,
// never hand-maintained.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { defaultAdapterRegistry, resolveAgentPluginProjection } = await import(
  new URL("../packages/cli/dist/index.js", import.meta.url).href
);

const registry = defaultAdapterRegistry();
const adapters = Object.values(registry);

// --- docs/harness-support.md -------------------------------------------------

const lines = [
  "# Harness support",
  "",
  "<!-- GENERATED by scripts/generate-harness-support.mjs -- do not edit. -->",
  "",
  "The single source for these facts is each adapter's `harness` metadata and",
  "capability profiles (`packages/adapter-*/src/{harness,profile}.ts`). The",
  "contract suite in `@hooknostic/testkit` audits every row.",
  "",
  "| Harness | Recommended target range | Validated ranges | Reference build | Fixtures |",
  "| --- | --- | --- | --- | --- |",
];
for (const adapter of adapters) {
  const meta = adapter.harness;
  lines.push(
    `| ${meta.displayName} (\`${adapter.id}\`) | \`${meta.recommendedRange}\` | ` +
      `${adapter
        .supportedHarnessVersions()
        .map((range) => `\`${range}\``)
        .join(", ")} | ` +
      `${meta.referenceVersion} | \`fixtures/${adapter.id}/${meta.fixtureDir}\` |`,
  );
}
lines.push("", "## Validation evidence", "");
for (const adapter of adapters) {
  const meta = adapter.harness;
  lines.push(`### ${meta.displayName}`, "");
  lines.push("| Version | Date | Method | Evidence | Established |", "| --- | --- | --- | --- | --- |");
  const resolution = adapter.capabilities({
    id: adapter.id,
    version: meta.recommendedRange,
    delivery: "project",
    output: ".",
  });
  for (const profile of resolution.profilesUsed) {
    for (const record of profile.source.validatedOn) {
      lines.push(
        `| ${record.version} | ${record.date} | ${record.method} | ` +
          `${record.artifact ? `\`${record.artifact}\`` : "—"} | ${record.what} |`,
      );
    }
  }
  lines.push("");
  if (adapter.projectComponentProfiles) {
    const projection = resolveAgentPluginProjection(
      { id: adapter.id, version: meta.recommendedRange, delivery: "project", output: "." },
      { profiles: adapter.projectComponentProfiles },
    );
    lines.push("#### Project delivery", "", "| Component | Support | Rationale |", "| --- | --- | --- |");
    for (const [component, support] of Object.entries(projection.matrix ?? {}))
      lines.push(`| \`${component}\` | ${support.level} | ${support.rationale ?? "—"} |`);
    lines.push("", "Project delivery validation records:", "");
    lines.push("| Version | Date | Method | Evidence | Established |", "| --- | --- | --- | --- | --- |");
    for (const profile of projection.profilesUsed) {
      for (const record of profile.source.validatedOn) {
        lines.push(
          `| ${record.version} | ${record.date} | ${record.method} | ` +
            `${record.artifact ? `\`${record.artifact}\`` : "—"} | ${record.what} |`,
        );
      }
    }
    lines.push("", "Project support is independent of package projection.", "");
  }
  if (adapter.agentPluginProjector) {
    const projection = resolveAgentPluginProjection(
      {
        id: adapter.id,
        version: meta.recommendedRange,
        delivery: adapter.supportedDeliveries()[0],
        output: ".",
      },
      adapter.agentPluginProjector,
    );
    lines.push("#### Agent Plugin projection", "");
    lines.push("| Component | Support | Rationale |", "| --- | --- | --- |");
    for (const [component, support] of Object.entries(projection.matrix ?? {})) {
      lines.push(`| \`${component}\` | ${support.level} | ${support.rationale ?? "—"} |`);
    }
    lines.push("", "Projection validation records:", "");
    lines.push("| Version | Date | Method | Evidence | Established |", "| --- | --- | --- | --- | --- |");
    for (const profile of projection.profilesUsed) {
      for (const record of profile.source.validatedOn) {
        lines.push(
          `| ${record.version} | ${record.date} | ${record.method} | ` +
            `${record.artifact ? `\`${record.artifact}\`` : "—"} | ${record.what} |`,
        );
      }
    }
    lines.push("");
  }
}
writeFileSync(resolve(ROOT, "docs/harness-support.md"), lines.join("\n") + "\n", "utf8");

console.log("harness-support generated");
