it("rejects invalid content, duplicate names and file/directory collisions", () => {
  for (const files of [
    [{ ...old, content: "%%%" }],
    [old, old],
    [old, { ...old, path: old.path.toUpperCase() }],
    [old, file(`${old.path}/child`, "x")],
  ]) {
    expect(() => validateManifest({ format: 1, headSha: sha, pr: 17, files })).toThrow();
  }
});

it("refuses truncated trees, symlinks, and gitlink ancestors", () => {
  const s = scenario();
  expect(() => planChanges(s.manifest, { ...s.tree, truncated: true })).toThrow("Incomplete git tree");
  expect(() => planChanges(s.manifest, { tree: [{ ...entry(old), mode: "120000" }] })).toThrow("Non-regular");
  expect(() => planChanges(s.manifest, { tree: [{ path: "examples", type: "commit" }] })).toThrow("Non-directory");
});

const dirs = [];
afterEach(() => {
  for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true });
});
it("regenerates from the root, removes stale output, and includes reports in the permitted snapshots", () => {
  const root = mkdtempSync(join(tmpdir(), "example-generation-"));
  dirs.push(root);
  for (const path of outputRoots) {
    mkdirSync(join(root, path), { recursive: true });
    writeFileSync(join(root, path, "removed.txt"), "stale");
  }
  const run = vi.fn((_command, args, options) => {
    expect(options.cwd).toBe(root);
    if (args.length === 1) return;
    const config = args.at(-1);
    const example = config.slice(0, -"/hooknostic.config.ts".length);
    mkdirSync(join(root, example, "dist"), { recursive: true });
    writeFileSync(join(root, example, "dist", "new.txt"), "new");
    writeFileSync(join(root, example, "hooknostic-build.json"), '{"digest":"new"}');
  });
  buildExamples(root, run);
  expect(run).toHaveBeenCalledTimes(5);
  expect(run.mock.calls.slice(-2).map((call) => call[1][1])).toEqual(["sync", "verify"]);
  const snapshot = collectManifest(root, sha, 17);
  for (const path of outputRoots) {
    expect(snapshot.files).toContainEqual(file(`${path}/hooknostic-build.json`, '{"digest":"new"}'));
    expect(snapshot.files.some((item) => item.path === `${path}/removed.txt`)).toBe(false);
    expect(existsSync(join(root, path, "..", "hooknostic-build.json"))).toBe(false);
  }
});
it("collects hidden outputs and observes deletions on the next snapshot", () => {
  const root = mkdtempSync(join(tmpdir(), "artifact-manifest-"));
  dirs.push(root);
  for (const dir of outputRoots) mkdirSync(join(root, dir), { recursive: true });
  const path = `${outputRoots[1]}/.hidden.json`;
  writeFileSync(join(root, path), "bytes");
  expect(collectManifest(root, sha, 17).files).toEqual([file(path, "bytes")]);
  rmSync(join(root, path));
  expect(collectManifest(root, sha, 17).files).toEqual([]);
});

it.skipIf(process.platform === "win32")("rejects symlink outputs in the producing job", () => {
  const root = mkdtempSync(join(tmpdir(), "artifact-symlink-"));
  dirs.push(root);
  for (const dir of outputRoots) mkdirSync(join(root, dir), { recursive: true });
  symlinkSync("/etc/passwd", join(root, outputRoots[0], "link"));
  expect(() => collectManifest(root, sha, 17)).toThrow("regular file");
});

