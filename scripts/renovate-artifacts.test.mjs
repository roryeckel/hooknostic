const sha = "a".repeat(40);
const newer = "b".repeat(40);
const repository = "owner/project";
const file = (path, content) => ({ path, content: Buffer.from(content).toString("base64") });
const old = file(`${outputRoots[0]}/claude/runtime/hooknostic.mjs`, "old bytes");
const updated = file(old.path, "new bytes");
const added = file(`${outputRoots[1]}/codex/.codex/new.json`, "new output");
const entry = (file) => ({ path: file.path, mode: "100644", type: "blob", sha: gitBlobSha(file.content) });

function scenario(files = [updated, added]) {
  const manifest = { format: 1, headSha: sha, pr: 17, files };
  const workflow = { path: workflowPath, id: 23 };
  const run = {
    id: 42,
    workflow_id: 23,
    run_attempt: 1,
    path: workflowPath,
    event: "pull_request",
    status: "completed",
    conclusion: "success",
    head_sha: sha,
    head_branch: "renovate/npm-dependencies",
    repository: { full_name: repository },
    head_repository: { full_name: repository },
    pull_requests: [{ number: 17 }],
  };
  const pr = {
    number: 17,
    state: "open",
    user: { login: "renovate[bot]", type: "Bot" },
    head: { repo: { full_name: repository }, ref: run.head_branch, sha },
    base: { repo: { full_name: repository } },
  };
  const jobs = { total_count: 1, jobs: [{ name: "generate", status: "completed", conclusion: "success" }] };
  const tree = {
    truncated: false,
    tree: [entry(old), { path: "package.json", type: "blob", mode: "100644", sha: newer }],
  };
  const writes = [];
  let reads = 0;
  const state = { manifest, workflow, run, pr, jobs, tree, writes, beforeCommit: () => {}, onWrite: () => {} };
  state.api = vi.fn(async (path, body) => {
    if (body) {
      writes.push(body);
      state.onWrite(body);
      return { data: { createCommitOnBranch: { commit: { oid: newer } } } };
    }
    if (path.endsWith("/actions/runs/42")) return run;
    if (path.endsWith("/actions/workflows/renovate-artifacts.yml")) return workflow;
    if (path.endsWith("/jobs?per_page=100")) return jobs;
    if (path.endsWith("/artifacts?per_page=100"))
      return { total_count: 1, artifacts: [{ id: 99, name: artifactName, size_in_bytes: 500, expired: false }] };
    if (path.endsWith("/pulls/17")) {
      if (++reads === 2) state.beforeCommit();
      return pr;
    }
    if (path.endsWith(`/git/trees/${sha}?recursive=1`)) return tree;
    throw new Error(`Unexpected API request ${path}`);
  });
  state.download = vi.fn(async () => manifest);
  state.apply = () => applyArtifacts({ repository, runId: 42, attempt: 1, api: state.api, download: state.download });
  return state;
}

it("commits changed bytes and added outputs from both examples using an atomic head check", async () => {
  const s = scenario();
  expect(await s.apply()).toBe("committed example artifacts");
  expect(s.writes).toHaveLength(1);
  const input = s.writes[0].variables.input;
  expect(input.branch).toEqual({ repositoryNameWithOwner: repository, branchName: s.pr.head.ref });
  expect(input.expectedHeadOid).toBe(sha);
  expect(input.fileChanges).toEqual({
    additions: [
      { path: updated.path, contents: Buffer.from("new bytes").toString("base64") },
      { path: added.path, contents: Buffer.from("new output").toString("base64") },
    ],
    deletions: [],
  });
});

it("does not commit when every generated byte already matches", async () => {
  const s = scenario([old]);
  expect(await s.apply()).toBe("no changes");
  expect(s.writes).toEqual([]);
});

it("deletes removed outputs, including an entirely emptied output set, without touching other files", async () => {
  const s = scenario([]);
  s.tree.tree.push(entry(added));
  expect(await s.apply()).toBe("committed example artifacts");
  expect(s.writes[0].variables.input.fileChanges).toEqual({
    additions: [],
    deletions: [{ path: old.path }, { path: added.path }],
  });
});

it("skips a stale head before reading the tree", async () => {
  const s = scenario();
  s.pr.head.sha = newer;
  expect(await s.apply()).toBe("stale head or closed PR");
  expect(s.writes).toEqual([]);
  expect(s.api.mock.calls.some(([path]) => path.includes("/git/trees/"))).toBe(false);
});

it("skips a head that moves while preparing changes", async () => {
  const s = scenario();
  s.beforeCommit = () => {
    s.pr.head.sha = newer;
  };
  expect(await s.apply()).toBe("stale head or closed PR");
  expect(s.writes).toEqual([]);
});

it("treats an atomic write conflict as stale and never retries the write", async () => {
  const s = scenario();
  s.onWrite = (body) => {
    expect(body.variables.input.expectedHeadOid).toBe(sha);
    s.pr.head.sha = newer;
    throw new Error("expectedHeadOid mismatch");
  };
  expect(await s.apply()).toBe("stale head or closed PR");
  expect(s.writes).toHaveLength(1);
});

it("propagates real commit failures when the head has not changed", async () => {
  const s = scenario();
  s.onWrite = () => {
    throw new Error("credential rejected");
  };
  await expect(s.apply()).rejects.toThrow("credential rejected");
});

it("skips superseded run attempts and closed PRs", async () => {
  const s = scenario();
  s.run.run_attempt = 2;
  expect(await s.apply()).toBe("stale attempt");
  expect(s.download).not.toHaveBeenCalled();
  s.run.run_attempt = 1;
  s.pr.state = "closed";
  expect(await s.apply()).toBe("stale head or closed PR");
  expect(s.writes).toEqual([]);
});

it("rejects foreign PRs, non-bot authors, mismatched associations, and non-Renovate branches", async () => {
  const mutations = [
    (s) => {
      s.pr.head.repo.full_name = "foreign/project";
    },
    (s) => {
      s.pr.base.repo.full_name = "foreign/project";
    },
    (s) => {
      s.pr.user.login = "human";
    },
    (s) => {
      s.pr.user.type = "User";
    },
    (s) => {
      s.pr.head.ref = "feature/update";
      s.run.head_branch = "feature/update";
    },
    (s) => {
      s.pr.head.ref = "renovate/different";
    },
    (s) => {
      s.run.pull_requests = [{ number: 18 }];
    },
    (s) => {
      s.manifest.headSha = newer;
    },
  ];
  for (const mutate of mutations) {
    const s = scenario();
    mutate(s);
    await expect(s.apply()).rejects.toThrow();
    expect(s.writes).toEqual([]);
  }
});

