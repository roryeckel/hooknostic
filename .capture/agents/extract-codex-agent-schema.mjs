// Regenerate the adapter's shape-only schemas from the versioned upstream sources.
import { writeFile } from "node:fs/promises";
import { register } from "node:module";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

register(new URL("../../scripts/ts-resolve-hook.mjs", import.meta.url));
const { codexAgentSchemaValidation } = await import("../../packages/adapter-codex/src/agent-native-source.ts");
const strip = (value, map = false) => Array.isArray(value) ? value.map((item) => strip(item))
  : value && typeof value === "object" ? Object.fromEntries(Object.entries(value)
    .filter(([key]) => map || !["description", "title", "default", "examples"].includes(key))
    .map(([key, child]) => [key, strip(child, ["properties", "definitions", "patternProperties"].includes(key))])) : value;
const schemas = [];
for (const record of codexAgentSchemaValidation) {
  const url = `https://raw.githubusercontent.com/openai/codex/rust-v${record.version}/codex-rs/core/config.schema.json`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  const schema = strip(await response.json());
  // RawAgentRoleFileToml flattens ConfigToml and adds standalone role metadata.
  schema.properties.nickname_candidates = { type: "array", minItems: 1, uniqueItems: true, items: { type: "string", pattern: "^[A-Za-z0-9 _-]*[A-Za-z0-9_-][A-Za-z0-9 _-]*$" } };
  schemas.push(schema);
}
await writeFile(new URL("../../packages/adapter-codex/src/agent-native-schema.ts", import.meta.url), await format(
  "// Generated by .capture/agents/extract-codex-agent-schema.mjs; do not edit.\n" +
  "// Derived from openai/codex ConfigToml schemas (OpenAI, Apache-2.0).\n" +
  "// Versions and provenance: agent-native-source.ts and .capture/agents/README.md.\n" +
  `export const codexAgentSchemas: readonly object[] = ${JSON.stringify(schemas, null, 2)};\n`, { ...await resolveConfig(fileURLToPath(new URL("../../packages/adapter-codex/src/agent-native-schema.ts", import.meta.url))), parser: "typescript" }));
const licenseResponse = await fetch(`https://raw.githubusercontent.com/openai/codex/rust-v${codexAgentSchemaValidation[0].version}/LICENSE`);
if (!licenseResponse.ok) throw new Error(`Upstream license: ${licenseResponse.status}`);
await writeFile(new URL("../../packages/adapter-codex/NOTICE", import.meta.url),
  "Codex ConfigToml schema snapshots\nCopyright OpenAI. Licensed under Apache-2.0.\n" +
  "Modified by removing descriptive/default metadata and adding standalone role metadata.\n" +
  "Versions and source links: .capture/agents/README.md.\n\n" + await licenseResponse.text());
console.log(`Generated ${schemas.length} Codex native agent schemas.`);
